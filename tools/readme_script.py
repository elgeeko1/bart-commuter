"""Copy bart-commuter-loader.js into README.md as a compact code block for copy and paste.

The copy drops comments and repeated blank lines, keeping Scriptable's header, the license lines, and
the code as written.

Usage: python3 tools/readme_script.py [--check | --print]
  --check  exit 1 when README.md does not hold the current copy
  --print  write the compact script to stdout instead of README.md
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SCRIPT = ROOT / "bart-commuter-loader.js"
README = ROOT / "README.md"
BEGIN = "<!-- BEGIN SCRIPT: generated by tools/readme_script.py; do not edit -->"
END = "<!-- END SCRIPT -->"
REPO_URL = "https://github.com/elgeeko1/bart-commuter"
# Scriptable reads the script icon from these first lines
SCRIPTABLE_HEADER_LINES = 3
KEPT_COMMENTS = ("// SPDX-",)
FENCE = "```"


class ReadmeError(Exception):
    pass


def compact(source: str) -> str:
    """Returns the script without comments or repeated blank lines."""
    lines = source.splitlines()
    header = lines[:SCRIPTABLE_HEADER_LINES]
    if not header[-1].startswith("// icon-color:"):
        raise ReadmeError("Scriptable header not found")
    kept = [line for line in lines if line.startswith(KEPT_COMMENTS)]
    body: list[str] = []
    in_block = False
    for line in lines[SCRIPTABLE_HEADER_LINES:]:
        text = line.strip()
        if in_block:
            in_block = not text.endswith("*/")
            continue
        if text.startswith("/*"):
            in_block = not text.endswith("*/")
            continue
        if text.startswith("//"):
            continue
        if not text and (not body or not body[-1]):
            continue
        body.append(line.rstrip())
    while body and not body[-1]:
        body.pop()
    if any(FENCE in line for line in body):
        raise ReadmeError(f"script contains {FENCE}")
    return "\n".join([*header, "", *kept, f"// {REPO_URL}", "", *body]) + "\n"


def with_script(readme: str, script: str) -> str:
    start = readme.find(BEGIN)
    end = readme.find(END)
    if start < 0 or end < start:
        raise ReadmeError(f"script block not found in {README.name}")
    block = f"{BEGIN}\n\n{FENCE}js\n{script}{FENCE}\n\n"
    return readme[:start] + block + readme[end:]


def main(argv: list[str]) -> int:
    assert __doc__ is not None
    parser = argparse.ArgumentParser(description=__doc__.strip().splitlines()[0])
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--check", action="store_true")
    mode.add_argument("--print", action="store_true")
    args = parser.parse_args(argv[1:])
    script = compact(SCRIPT.read_text(encoding="utf-8"))
    if args.print:
        sys.stdout.write(script)
        return 0
    readme = README.read_text(encoding="utf-8")
    updated = with_script(readme, script)
    if args.check:
        if updated != readme:
            print(f"{README.name} script block is out of date", file=sys.stderr)
            return 1
        return 0
    README.write_text(updated, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
