BEGIN = "// BEGIN NETWORK: generated by tools/generate_network.py from BART's static GTFS; do not edit"
END = "// END NETWORK"
RAIL_ROUTE_TYPE = "1"
ROUTE_NAME = re.compile(r"^(?P<line>[A-Za-z]+)-(?P<dir>[NS])$")

