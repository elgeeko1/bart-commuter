class NetworkError(Exception):
    """The GTFS feed does not match the shape the widget tables assume."""


@dataclass(frozen=True)
class Route:
    number: int
    line: str
    direction: str
    color: str
    stations: tuple[str, ...]
    skips: tuple[str, ...]


def read_table(archive: zipfile.ZipFile, name: str) -> Iterator[dict[str, str]]:
    """Yield the rows of one GTFS file in the archive."""
    with archive.open(name) as raw:
        yield from csv.DictReader(io.TextIOWrapper(raw, encoding="utf-8-sig"))


def dedupe(stations: list[str]) -> tuple[str, ...]:
    """Collapse consecutive stops at different platforms of the same station."""
    out: list[str] = []
    for station in stations:
        if not out or out[-1] != station:
            out.append(station)
    return tuple(out)


def is_subsequence(part: tuple[str, ...], whole: tuple[str, ...]) -> bool:
    remaining = iter(whole)
    return all(station in remaining for station in part)


def skipped(pattern: tuple[str, ...], full: tuple[str, ...]) -> set[str]:
    """Return the stations of full that pattern passes without stopping at."""
    span = full[full.index(pattern[0]) : full.index(pattern[-1]) + 1]
    return set(span) - set(pattern)


def load_platforms(archive: zipfile.ZipFile) -> dict[str, list[str]]:
    """Map each station code to its platform stop ids."""
    platforms: dict[str, list[str]] = defaultdict(list)
    for stop in read_table(archive, "stops.txt"):
        # GTFS treats an empty location_type as 0, a stop or platform
        if stop["location_type"] in ("", "0") and stop["parent_station"]:
            platforms[stop["parent_station"]].append(stop["stop_id"])
    if set(platforms) != set(NAMES):
        raise NetworkError(
            f"stations differ from NAMES: {sorted(set(platforms) ^ set(NAMES))}"
        )
    return {abbr: sorted(ids) for abbr, ids in sorted(platforms.items())}


def load_routes(
    archive: zipfile.ZipFile, platforms: dict[str, list[str]]
) -> list[Route]:
    """Build each rail route's full station order from the stop sequences of its trips."""
    station_of = {stop_id: abbr for abbr, ids in platforms.items() for stop_id in ids}
    rail = {
        r["route_id"]: r
        for r in read_table(archive, "routes.txt")
        if r["route_type"] == RAIL_ROUTE_TYPE
    }
    route_of = {
        t["trip_id"]: t["route_id"]
        for t in read_table(archive, "trips.txt")
        if t["route_id"] in rail
    }

    stops: dict[str, list[tuple[int, str]]] = defaultdict(list)
    for st in read_table(archive, "stop_times.txt"):
        if st["trip_id"] in route_of:
            stops[st["trip_id"]].append(
                (int(st["stop_sequence"]), station_of[st["stop_id"]])
            )

    patterns: dict[str, set[tuple[str, ...]]] = defaultdict(set)
    for trip_id, seq in stops.items():
        patterns[route_of[trip_id]].add(dedupe([abbr for _, abbr in sorted(seq)]))

    routes: list[Route] = []
    for route_id, row in rail.items():
        match = ROUTE_NAME.match(row["route_short_name"])
        if not match:
            raise NetworkError(f"unexpected route name: {row['route_short_name']}")
        if not patterns[route_id]:
            raise NetworkError(f"route {route_id} has no trips")
        full = max(patterns[route_id], key=len)
        for pattern in patterns[route_id]:
            if not is_subsequence(pattern, full):
                raise NetworkError(
                    f"route {route_id} trip {' '.join(pattern)} leaves {' '.join(full)}"
                )
        routes.append(
            Route(
                number=int(route_id),
                line=match["line"].upper(),
                direction=match["dir"].lower(),
                color=f"#{row['route_color'].lower()}",
                stations=full,
                skips=tuple(
                    sorted(set().union(*(skipped(p, full) for p in patterns[route_id])))
                ),
            )
        )
    return sorted(routes, key=lambda r: r.number)


def render(platforms: dict[str, list[str]], routes: list[Route]) -> str:
    colors = {r.line: r.color for r in routes}
    lines = [BEGIN, "const STATIONS = {"]
    lines += [
        f"  {json.dumps(abbr)}: {{ name: {json.dumps(NAMES[abbr])}, platforms: {json.dumps(ids)} }},"
        for abbr, ids in platforms.items()
    ]
    lines += ["};", "const LINE_COLORS = {"]
    lines += [
        f"  {line}: {json.dumps(color)}," for line, color in sorted(colors.items())
    ]
    lines += [
        "};",
        "// number is the schedule API's route number; stations are in travel order, and some",
        "// trips pass skips without stopping",
        "const ROUTES = [",
    ]
    lines += [
        f"  {{ number: {r.number}, line: {json.dumps(r.line)}, dir: {json.dumps(r.direction)}, "
        f"stations: {json.dumps(list(r.stations))}, skips: {json.dumps(list(r.skips))} }},"
        for r in routes
    ]
    lines += ["];", END]
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    if len(argv) != 2:
        assert __doc__ is not None
        print(__doc__.strip().splitlines()[-1], file=sys.stderr)
        return 2
    with zipfile.ZipFile(argv[1]) as archive:
        platforms = load_platforms(archive)
        routes = load_routes(archive, platforms)
    source = SCRIPT.read_text(encoding="utf-8")
    pattern = re.compile(
        rf"^{re.escape(BEGIN)}$.*?^{re.escape(END)}$", re.MULTILINE | re.DOTALL
    )
    if not pattern.search(source):
        raise NetworkError(f"generated block not found in {SCRIPT}")
    SCRIPT.write_text(
        pattern.sub(lambda _: render(platforms, routes), source, count=1),
        encoding="utf-8",
    )
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
